export type DictKey = keyof typeof ZH

const DICTS: Record<Lang, Record<DictKey, string>> = { zh: ZH, en: EN }

function detect(): Lang {
  try {
    const raw = window.localStorage.getItem(STORAGE_KEY)
    if (raw === 'zh' || raw === 'en') return raw
  } catch {
    // 忽略：回落到浏览器语言
  }
  const nav = typeof navigator !== 'undefined' ? navigator.language.toLowerCase() : 'zh'
  return nav.startsWith('zh') ? 'zh' : 'en'
}

let current: Lang = typeof window === 'undefined' ? 'zh' : detect()

export function currentLang(): Lang {
  return current
}

export function setLang(lang: Lang): void {
  current = lang
  try {
    window.localStorage.setItem(STORAGE_KEY, lang)
  } catch {
    // 只在本次会话生效
  }
  for (const listener of listeners) listener()
}

export function toggleLang(): void {
  setLang(current === 'zh' ? 'en' : 'zh')
}

function subscribe(listener: () => void): () => void {
  listeners.add(listener)
  return () => listeners.delete(listener)
}

/** 翻译（模块级，读当前语言）：`{n}` 形式占位符按 vars 替换。 */
export function t(key: DictKey, vars?: Record<string, string | number>): string {
  const text = DICTS[current][key] ?? ZH[key] ?? key
  if (vars === undefined) return text
  return text.replace(/\{(\w+)\}/g, (whole, name: string) =>
    vars[name] !== undefined ? String(vars[name]) : whole,
  )
}

/** 组件里用这个：订阅语言变化，切换即重渲染。 */
export function useT(): typeof t {
  useSyncExternalStore(subscribe, currentLang)
  return t
}
