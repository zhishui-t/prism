/** 锚点/别名/标签检查（值或序列项起点）。 */
function checkUnsupportedScalar(text: string, line: number): void {
  if (/^[&*!]/.test(text)) {
    throw new FrontmatterError('parse_unsupported', `不支持的语法（锚点/别名/标签）：${text.slice(0, 16)}`, line)
  }
}

/** 解析行内值：标量 / flow 数组 / flow 映射。 */
function parseInlineValue(text: string, line: number): FrontmatterValue {
  const s = text.trim()
  if (s === '' || s === 'null' || s === '~' || s === 'Null' || s === 'NULL') return null
  if (s === 'true' || s === 'True' || s === 'TRUE') return true
  if (s === 'false' || s === 'False' || s === 'FALSE') return false
  if (s.startsWith('"')) return parseDoubleQuoted(s, line)
  if (s.startsWith("'")) return parseSingleQuoted(s, line)
  if (s.startsWith('[') && s.endsWith(']')) return parseFlowSeq(s, line)
  if (s.startsWith('{') && s.endsWith('}')) return parseFlowMap(s, line)
  if (/^[+-]?(\d+\.?\d*|\.\d+)([eE][+-]?\d+)?$/.test(s)) return Number(s)
  if (/^0x[0-9a-fA-F]+$/.test(s)) return Number(s)
  return s
}

function parseDoubleQuoted(s: string, line: number): FrontmatterValue {
  if (!s.endsWith('"') || s.length < 2) {
    throw new FrontmatterError('parse_failed', `第 ${line} 行双引号标量未闭合`, line)
  }
  try {
    return JSON.parse(s) as FrontmatterValue
  } catch {
    // JSON 不接受的转义（如 \xNN）→ 明确不支持，而非静默错值
    throw new FrontmatterError('parse_unsupported', `第 ${line} 行双引号转义不受支持`, line)
  }
}

function parseSingleQuoted(s: string, line: number): FrontmatterValue {
  if (!s.endsWith("'") || s.length < 2) {
    throw new FrontmatterError('parse_failed', `第 ${line} 行单引号标量未闭合`, line)
  }
  return s.slice(1, -1).replace(/''/g, "'")
}

/** 解析行内 flow 数组：按不在引号/嵌套内的顶层逗号切分。 */
function parseFlowSeq(s: string, line: number): FrontmatterValue[] {
  const inner = s.slice(1, -1).trim()
  if (inner === '') return []
  return splitTopLevel(inner).map((p) => parseInlineValue(p, line))
}

/** 解析行内 flow 映射 `{k: v, ...}`。 */
function parseFlowMap(s: string, line: number): { [key: string]: FrontmatterValue } {
  const inner = s.slice(1, -1).trim()
  const out: { [key: string]: FrontmatterValue } = {}
  if (inner === '') return out
  for (const part of splitTopLevel(inner)) {
    const idx = findFlowKeySeparator(part)
    if (idx === -1) {
      throw new FrontmatterError('parse_failed', `flow 映射项缺少冒号：${part.slice(0, 20)}`, line)
    }
    const key = unquoteKey(part.slice(0, idx).trim())
    out[key] = parseInlineValue(part.slice(idx + 1).trim(), line)
  }
  return out
}

/** 按不在引号/嵌套括号内的顶层逗号切分。 */
function splitTopLevel(s: string): string[] {
  const parts: string[] = []
  let depth = 0
  let inQuote: string | null = null
  let current = ''
  for (const ch of s) {
    if (inQuote) {
      current += ch
      if (ch === inQuote) inQuote = null
      continue
    }
    if (ch === '"' || ch === "'") {
      inQuote = ch
      current += ch
      continue
    }
    if (ch === '[' || ch === '{') depth++
    if (ch === ']' || ch === '}') depth--
    if (ch === ',' && depth === 0) {
      parts.push(current.trim())
      current = ''
      continue
    }
    current += ch
  }
  if (current.trim() !== '') parts.push(current.trim())
  return parts
}

/** 找到 `key:` 分隔符：第一个不在引号/flow 括号内的 `:`（行尾冒号或后随空格）。 */
function findKeySeparator(text: string): number {
  let inQuote: string | null = null
  let depth = 0
  for (let i = 0; i < text.length; i++) {
    const ch = text[i]
    if (inQuote) {
      if (ch === inQuote) inQuote = null
      continue
    }
    if (ch === '"' || ch === "'") {
      inQuote = ch
      continue
    }
    if (ch === '[' || ch === '{') depth++
    if (ch === ']' || ch === '}') depth--
    if (ch === ':' && depth === 0 && (i + 1 === text.length || text[i + 1] === ' ')) return i
  }
  return -1
}

/** flow 映射里的 key 分隔（key 在前，取第一个引号外冒号即可）。 */
function findFlowKeySeparator(part: string): number {
  let inQuote: string | null = null
  for (let i = 0; i < part.length; i++) {
    const ch = part[i]
    if (inQuote) {
      if (ch === inQuote) inQuote = null
      continue
    }
    if (ch === '"' || ch === "'") {
      inQuote = ch
      continue
    }
    if (ch === ':') return i
  }
  return -1
}

function unquoteKey(key: string): string {
  if (key.length >= 2 && ((key.startsWith('"') && key.endsWith('"')) || (key.startsWith("'") && key.endsWith("'")))) {
    return key.slice(1, -1)
  }
  return key
}

