/** 序列化为 frontmatter 文本（含首尾 --- 行）。 */
export function serializeFrontmatter(data: FrontmatterData): string {
  const body = emitBlockMap(data, 0)
  return `---\n${body}\n---\n`
}

/** 生成完整 md 文件：frontmatter（自带结尾换行）+ 正文。 */
export function renderMarkdownFile(data: FrontmatterData, content: string): string {
  return `${serializeFrontmatter(data)}${content.endsWith('\n') || content === '' ? content : `${content}\n`}`
}

/**
 * 标量安全输出（harness §2.1 引号约束）：
 * 含冒号/特殊字符/看似数字或布尔/空串的值一律 JSON 双引号（合法的 YAML 双引号标量）。
 */
export function emitScalar(s: string): string {
  if (s === '') return '""'
  if (
    SAFE_PLAIN_RE.test(s) &&
    Number.isNaN(Number(s)) &&
    !['true', 'false', 'null', '~', 'True', 'False', 'Null'].includes(s)
  ) {
    return s
  }
  return JSON.stringify(s)
}

function emitBlockMap(data: FrontmatterData, indent: number): string {
  const pad = ' '.repeat(indent)
  const chunks: string[] = []
  for (const [key, value] of Object.entries(data)) {
    // 首行由这里补缩进；子行（嵌套块）已自带更深缩进
    chunks.push(pad + emitEntry(key, value, indent, pad))
  }
  return chunks.join('\n')
}

/** 单个 `key: value` 条目（可能展开为多行；首行**不带**缩进，由调用方补；子行已自带缩进）。 */
function emitEntry(key: string, value: FrontmatterValue, indent: number, pad: string): string {
  if (value === null) return `${key}: null`
  if (typeof value === 'string') return `${key}: ${emitScalar(value)}`
  if (typeof value === 'number' || typeof value === 'boolean') return `${key}: ${String(value)}`
  if (Array.isArray(value)) {
    if (value.length === 0) return `${key}: []`
    const items = value.map((item) => emitSeqItem(item, indent, pad))
    return [`${key}:`, ...items].join('\n')
  }
  const entries = Object.entries(value)
  if (entries.length === 0) return `${key}: {}`
  return [`${key}:`, emitBlockMap(value, indent + 2)].join('\n')
}

function emitSeqItem(item: FrontmatterValue, indent: number, pad: string): string {
  if (item === null) return `${pad}- null`
  if (typeof item === 'string') return `${pad}- ${emitScalar(item)}`
  if (typeof item === 'number' || typeof item === 'boolean') return `${pad}- ${String(item)}`
  if (Array.isArray(item)) {
    return [`${pad}-`, emitBlockValue(item, indent + 2)].join('\n')
  }
  const entries = Object.entries(item)
  if (entries.length === 0) return `${pad}- {}`
  const innerPad = ' '.repeat(indent + 2)
  const lines = entries.map(([k, v], idx) => {
    const body = emitEntry(k, v, indent + 2, innerPad)
    return (idx === 0 ? `${pad}- ` : innerPad) + body
  })
  return lines.join('\n')
}

function emitBlockValue(value: FrontmatterValue, indent: number): string {
  if (Array.isArray(value)) {
    const pad = ' '.repeat(indent)
    return value.map((item) => emitSeqItem(item, indent, pad)).join('\n')
  }
  return emitBlockMap(value as FrontmatterData, indent)
}
